"""
PDF generation service using fpdf2 (pure Python, no system deps).
Creates invoice PDFs and approval stamps.
"""

from io import BytesIO
from datetime import datetime, timezone, timedelta
from fpdf import FPDF

IST = timezone(timedelta(hours=5, minutes=30))


class InvoicePDF(FPDF):
    """Custom PDF class for invoice generation."""

    def __init__(self):
        super().__init__()
        self.set_auto_page_break(auto=True, margin=20)

    def header_block(self, invoice_number: str):
        self.set_font("Helvetica", "B", 22)
        self.set_text_color(67, 97, 238)
        self.cell(0, 12, "INVOICE", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font("Helvetica", "", 11)
        self.set_text_color(100, 100, 100)
        self.cell(0, 8, invoice_number, align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(67, 97, 238)
        self.set_line_width(0.8)
        self.line(20, self.get_y() + 2, 190, self.get_y() + 2)
        self.ln(10)

    def info_row(self, label: str, value: str, bold_value: bool = False):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(100, 100, 100)
        self.cell(35, 6, label, new_x="END")
        style = "B" if bold_value else ""
        self.set_font("Helvetica", style, 10)
        self.set_text_color(30, 30, 30)
        self.cell(0, 6, value, new_x="LMARGIN", new_y="NEXT")

    def section_title(self, title: str):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(67, 97, 238)
        self.cell(0, 8, title.upper(), new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(200, 200, 200)
        self.line(20, self.get_y(), 190, self.get_y())
        self.ln(3)

    def add_table_row(self, col1: str, col2: str, is_header: bool = False, is_total: bool = False):
        if is_header:
            self.set_fill_color(67, 97, 238)
            self.set_text_color(255, 255, 255)
            self.set_font("Helvetica", "B", 10)
        elif is_total:
            self.set_fill_color(67, 97, 238)
            self.set_text_color(255, 255, 255)
            self.set_font("Helvetica", "B", 11)
        else:
            self.set_fill_color(248, 249, 250)
            self.set_text_color(30, 30, 30)
            self.set_font("Helvetica", "", 10)

        self.cell(130, 10, f"  {col1}", fill=True, new_x="END")
        self.cell(50, 10, col2, align="R", fill=True, new_x="LMARGIN", new_y="NEXT")

    def stamp_overlay(self, text: str, color: tuple):
        self.set_font("Helvetica", "B", 36)
        self.set_text_color(*color)
        self.set_draw_color(*color)
        x = 50
        y = self.get_y() + 30
        self.set_xy(x, y)
        self.set_line_width(1.5)
        # Draw border rectangle
        self.rect(x - 5, y - 5, 110, 25)
        self.cell(100, 20, text, align="C")

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
        self.cell(0, 10, f"Generated by InvoiceFlow on {now}", align="C")


class ApprovalOverlayPDF(FPDF):
    """Single-page transparent approval summary to overlay on original invoice PDF."""

    def __init__(self, page_width: float = 210, page_height: float = 297):
        super().__init__()
        self.page_width = page_width
        self.page_height = page_height

    def build_overlay(
        self,
        invoice_number: str,
        approval_chain: list[dict],
        submitted_at: str,
        remarks: str = "",
    ):
        """
        Build a single-page overlay with approval summary.
        Each approval_chain entry: {stage_name, role, actor_name, acted_at, comment}
        The overlay is placed at the bottom of the page with a semi-transparent background.
        """
        self.add_page(orientation="P", format=(self.page_width, self.page_height))

        # Background bar at the bottom
        bar_height = 48 + len(approval_chain) * 7
        bar_y = self.page_height - bar_height - 10

        # Semi-transparent background (light gray)
        self.set_fill_color(245, 245, 245)
        self.set_draw_color(200, 200, 200)
        self.set_line_width(0.3)
        self.rect(10, bar_y, self.page_width - 20, bar_height, style="DF")

        # Header line
        self.set_xy(15, bar_y + 3)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(67, 97, 238)
        self.cell(0, 5, "APPROVAL SUMMARY", new_x="LMARGIN", new_y="NEXT")

        # Divider
        self.set_draw_color(67, 97, 238)
        self.set_line_width(0.4)
        self.line(15, self.get_y() + 1, self.page_width - 15, self.get_y() + 1)
        self.ln(3)

        # Approved stamp
        self.set_xy(15, self.get_y())
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(46, 204, 113)
        self.cell(25, 5, "APPROVED", new_x="END")
        self.set_font("Helvetica", "", 7)
        self.set_text_color(80, 80, 80)
        self.cell(0, 5, f"{invoice_number}  |  {submitted_at}", new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

        # Approval chain rows
        self.set_font("Helvetica", "", 7)
        for entry in approval_chain:
            self.set_xy(15, self.get_y())
            # Stage + role
            self.set_text_color(60, 60, 60)
            self.set_font("Helvetica", "B", 7)
            self.cell(55, 5, entry.get("stage_name", ""), new_x="END")
            # Actor
            self.set_font("Helvetica", "", 7)
            self.set_text_color(40, 40, 40)
            self.cell(50, 5, entry.get("actor_name", ""), new_x="END")
            # Date
            self.set_text_color(100, 100, 100)
            self.cell(0, 5, entry.get("acted_at", ""), new_x="LMARGIN", new_y="NEXT")

        # Remarks if any
        if remarks:
            self.set_xy(15, self.get_y() + 1)
            self.set_font("Helvetica", "I", 6)
            self.set_text_color(120, 120, 120)
            remark_text = remarks[:80] + ("..." if len(remarks) > 80 else "")
            self.cell(0, 4, f"Remarks: {remark_text}", new_x="LMARGIN", new_y="NEXT")


class StampPDF(FPDF):
    """Standalone approval stamp page."""

    def __init__(self):
        super().__init__()

    def add_stamp(
        self,
        text: str,
        color: tuple,
        invoice_number: str,
        vendor_name: str,
        amount: float,
        actor_name: str,
        acted_at: str,
        comment: str = "",
        currency: str = "INR",
    ):
        self.add_page()
        self.set_font("Helvetica", "B", 42)
        self.set_text_color(*color)
        self.set_draw_color(*color)
        self.set_line_width(2)

        # Stamp box
        x = 35
        y = 80
        self.rect(x, y, 140, 40)
        self.set_xy(x, y + 5)
        self.cell(140, 30, text, align="C")

        # Details below stamp
        self.set_xy(20, y + 55)
        self.set_font("Helvetica", "", 12)
        self.set_text_color(100, 100, 100)
        self.cell(0, 8, f"Invoice: {invoice_number}", align="C", new_x="LMARGIN", new_y="NEXT")
        self.cell(0, 8, f"Vendor: {vendor_name}", align="C", new_x="LMARGIN", new_y="NEXT")
        self.cell(0, 8, f"Amount: {currency} {amount:,.2f}", align="C", new_x="LMARGIN", new_y="NEXT")
        self.cell(0, 8, f"Acted on: {acted_at} by {actor_name}", align="C", new_x="LMARGIN", new_y="NEXT")
        if comment:
            self.cell(0, 8, f"Comment: {comment}", align="C", new_x="LMARGIN", new_y="NEXT")


class PDFService:
    """Generate and manipulate invoice PDFs."""

    STAMP_COLORS = {
        "approved": (46, 204, 113),
        "rejected": (231, 76, 60),
        "under_review": (243, 156, 18),
    }

    STAMP_TEXT = {
        "approved": "APPROVED",
        "rejected": "REJECTED",
        "under_review": "UNDER REVIEW",
    }

    WORKFLOW_STAGES = [
        {"order": 1, "name": "Accountant 1 Verification"},
        {"order": 2, "name": "Accountant 2 Verification"},
        {"order": 3, "name": "Manager Approval"},
        {"order": 4, "name": "CEO Final Approval"},
    ]

    @staticmethod
    def generate_invoice_pdf(
        *,
        invoice_number: str,
        vendor_name: str,
        amount: float,
        status: str,
        submitted_at: str,
        submitter_name: str,
        department: str = "",
        remarks: str = "",
        currency: str = "INR",
        stamp_text: str = "",
        stamp_color: str = "",
    ) -> bytes:
        """Generate a PDF for an invoice."""
        pdf = InvoicePDF()
        pdf.add_page()

        # Header
        pdf.header_block(invoice_number)

        # Info section
        pdf.section_title("Invoice Details")
        pdf.info_row("Number:", invoice_number)
        pdf.info_row("Date:", submitted_at)
        pdf.info_row("Status:", status.upper())
        pdf.ln(3)

        pdf.section_title("Vendor")
        pdf.info_row("Name:", vendor_name)
        pdf.ln(3)

        pdf.section_title("Submitted By")
        pdf.info_row("Name:", submitter_name)
        if department:
            pdf.info_row("Department:", department)
        pdf.ln(5)

        # Amount table
        pdf.section_title("Amount")
        pdf.add_table_row("Description", "Amount", is_header=True)
        pdf.add_table_row(
            f"{vendor_name} - Invoice {invoice_number}",
            f"{currency} {amount:,.2f}",
        )
        pdf.add_table_row("Total", f"{currency} {amount:,.2f}", is_total=True)
        pdf.ln(5)

        # Remarks
        if remarks:
            pdf.section_title("Remarks")
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(30, 30, 30)
            pdf.multi_cell(0, 6, remarks)
            pdf.ln(5)

        # Status stamp
        if stamp_text and stamp_color:
            color = PDFService.STAMP_COLORS.get(stamp_color, (100, 100, 100))
            pdf.stamp_overlay(stamp_text, color)

        return bytes(pdf.output())

    @staticmethod
    def generate_approval_stamp(
        *,
        invoice_number: str,
        vendor_name: str,
        amount: float,
        status: str,
        actor_name: str,
        acted_at: str,
        comment: str = "",
        currency: str = "INR",
    ) -> bytes:
        """Generate a standalone approval stamp page as PDF."""
        stamp_text = PDFService.STAMP_TEXT.get(status, status.upper())
        color = PDFService.STAMP_COLORS.get(status, (100, 100, 100))

        pdf = StampPDF()
        pdf.add_stamp(
            text=stamp_text,
            color=color,
            invoice_number=invoice_number,
            vendor_name=vendor_name,
            amount=amount,
            actor_name=actor_name,
            acted_at=acted_at,
            comment=comment,
            currency=currency,
        )

        return bytes(pdf.output())

    @staticmethod
    def build_approval_chain_from_history(history: list[dict]) -> list[dict]:
        """Build structured approval chain from invoice action history."""
        approvals = [h for h in history if h.get("action") == "approve"]
        chain = []
        for i, stage in enumerate(PDFService.WORKFLOW_STAGES):
            approval = approvals[i] if i < len(approvals) else None
            acted_at = ""
            if approval and approval.get("created_at"):
                dt = datetime.fromisoformat(approval["created_at"].replace("Z", "+00:00")).astimezone(IST)
                acted_at = dt.strftime("%d %b %Y, %I:%M %p")
            chain.append({
                "stage_name": stage["name"],
                "role": stage["name"],
                "actor_name": approval["actor_name"] if approval else "-",
                "acted_at": acted_at or "-",
            })
        return chain

    @staticmethod
    def generate_approval_overlay_pdf(
        *,
        page_width: float,
        page_height: float,
        invoice_number: str,
        approval_chain: list[dict],
        submitted_at: str,
        remarks: str = "",
    ) -> bytes:
        """Generate a single-page transparent overlay PDF with approval summary."""
        overlay = ApprovalOverlayPDF(page_width=page_width, page_height=page_height)
        overlay.build_overlay(
            invoice_number=invoice_number,
            approval_chain=approval_chain,
            submitted_at=submitted_at,
            remarks=remarks,
        )
        return bytes(overlay.output())

    @staticmethod
    def merge_pdfs(original_pdf: bytes, stamp_pdf: bytes) -> bytes:
        """Merge original invoice PDF with approval stamp PDF (append as new page)."""
        from PyPDF2 import PdfReader, PdfWriter

        writer = PdfWriter()

        # Add original invoice pages
        original_reader = PdfReader(BytesIO(original_pdf))
        for page in original_reader.pages:
            writer.add_page(page)

        # Add stamp page
        stamp_reader = PdfReader(BytesIO(stamp_pdf))
        for page in stamp_reader.pages:
            writer.add_page(page)

        output = BytesIO()
        writer.write(output)
        return output.getvalue()

    @staticmethod
    def overlay_on_original_pdf(original_pdf: bytes, overlay_pdf: bytes) -> bytes:
        """Overlay approval summary directly onto the last page of the original PDF."""
        from PyPDF2 import PdfReader, PdfWriter

        original_reader = PdfReader(BytesIO(original_pdf))
        overlay_reader = PdfReader(BytesIO(overlay_pdf))
        writer = PdfWriter()

        overlay_page = overlay_reader.pages[0]

        for i, page in enumerate(original_reader.pages):
            if i == len(original_reader.pages) - 1:
                # Overlay on the last page
                page.merge_page(overlay_page)
            writer.add_page(page)

        output = BytesIO()
        writer.write(output)
        return output.getvalue()
